/* Export a reconstructed knight into the existing procedural skeleton. Coordinates normalised to height. */
import fs from 'node:fs';
const [input,output]=process.argv.slice(2);
if(!input||!output) throw new Error('Usage: node tools/lab/rig-split.mjs reconstruction.json src/models/hero_knight.js');
const d=JSON.parse(fs.readFileSync(input,'utf8'));
const data=JSON.stringify({height:d.height,palette:d.palette,vox:d.vox,view:d.view});
fs.writeFileSync(output,`/* Copyright (c) 2026 Merchant Protocol. All rights reserved. */
/* Reference-lifted knight. Generated by tools/lab/rig-split.mjs; see ASSET-LAB.md.
   Hidden surfaces use the reconstructed mesh prior, not verified reference geometry. */
(function(G){
const D=${data};
G.K.Models.register('hero_knight',({VoxelModel,GreedyMesher})=>{
 const h=D.height, q=h/64, M=new VoxelModel('hd_knight',{size:1.56/h,height:1.56,style:'swing',mesher:new GreedyMesher(),rest:{}});
 const spec={hips:[[0,30,0],null],torso:[[0,33,0],'hips'],head:[[0,49,0],'torso'],armR:[[-10,45,0],'torso'],weapon:[[-12,26,6],'armR'],armL:[[10,45,0],'torso'],shield:[[12,29,8],'armL'],cape:[[0,45,-5],'torso'],legR:[[-5,29,0],'hips'],legL:[[5,29,0],'hips']};
 const parts={};for(const [n,[p,parent]] of Object.entries(spec))parts[n]=M.part(n,p.map(v=>v*q),parent,{jitter:0});
 const palette=D.palette.map(c=>new G.THREE.Color('rgb('+c.map(Math.round).join(',')+')')).map(c=>[c.r,c.g,c.b]);
 for(let i=0;i<D.vox.length;i+=4){const [x,y,z,j]=D.vox.slice(i,i+4),X=x/q,Y=y/q,Z=z/q;
  let n='torso';
  if(Y>=49)n='head';
  else if(X < -11 && Y<28)n='weapon';
  else if(X>7 && Z>3 && Y<39 && Y>9)n='shield';
  else if(Y<29)n=Z < -4 && Y>7?'cape':(X<0?'legR':'legL');
  else if(Z < -5 && Y<46)n='cape';
  else if(Math.abs(X)>10)n=X<0?'armR':'armL';
  else if(Y<34)n='hips';
  parts[n].set(x,y,z,palette[j]);
 }
 return M;
},{kind:'rig',role:'knight',title:'Knight',view:D.view});
})(typeof window!=='undefined'?window:globalThis);
`);
console.log(output, d.vox.length/4,'voxels');
